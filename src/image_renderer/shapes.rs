pub(super) fn render(resource: &DynamicImage, options: &RenderOptions) -> Result<Frame> {
    options.validate()?;
    if options.dither || options.edges || options.edge_glyphs || options.ramp != RAMPS[0].1 {
        return Err("Shape matching chooses from all 95 characters, so it takes no dithering, edge tracing, edge characters or ramp".into());
    }
    check_pixels(resource.width(), resource.height())?;
    let height = options.output_height(resource.width(), resource.height());
    let count = dimensions(options.width, height)?;
    // Grey before resizing, so the resize works on 1 channel rather than 4: at 512 columns
    // the resized picture is 4096 pixels square.
    let grey: Vec<u8> = resource
        .to_rgba8()
        .pixels()
        .map(|pixel| (gray(pixel, options.background) * 255.0).round() as u8)
        .collect();
    let grey = GrayImage::from_raw(resource.width(), resource.height(), grey)
        .expect("one grey byte for each pixel");
    let resized = resize(
        &grey,
        (options.width * CELL.0) as u32,
        (height * CELL.1) as u32,
        FilterType::Triangle,
    );
    // Contrast, gamma and inversion for each of the 256 greys, rather than for each pixel.
    let tone: [f64; 256] = std::array::from_fn(|level| adjust(level as f64 / 255.0, options));
    let mut cells = Vec::with_capacity(count);
    for index in 0..count {
        let (left, top) = (
            index % options.width * CELL.0,
            index / options.width * CELL.1,
        );
        // Each bitmap pixel covers 2 picture pixels, one above the other.
        let mut ink = [[0.0; 8]; 8];
        for (row, sums) in ink.iter_mut().enumerate() {
            for (column, sum) in sums.iter_mut().enumerate() {
                for y in [top + 2 * row, top + 2 * row + 1] {
                    let [level] = resized.get_pixel((left + column) as u32, y as u32).0;
                    *sum += tone[usize::from(level)];
                }
            }
        }
        cells.push(best(&ink));
    }
    Frame::new(options.width, height, cells)
}

/// The character whose bitmap, ink at 1 and paper at 0, is nearest the cell by least squares.
/// Each cell's own sum of squares is the same for every character, so the cost is the inked
/// pixel count less twice the cell's ink under the bitmap. Ties go to the lower code.
fn best(ink: &[[f64; 8]; 8]) -> u8 {
    let mut chosen = (f64::INFINITY, b' ');
    for (code, bitmap) in (b' '..=b'~').zip(&BITMAPS) {
        let (mut inked, mut covered) = (0, 0.0);
        for (row, &bits) in bitmap.iter().enumerate() {
            inked += 2 * bits.count_ones();
            let mut rest = bits;
            while rest != 0 {
                covered += ink[row][rest.trailing_zeros() as usize];
                rest &= rest - 1;
            }
        }
        let cost = f64::from(inked) - 2.0 * covered;
        if cost < chosen.0 {
            chosen = (cost, code);
        }
    }
    chosen.1
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A cell whose ink is exactly `code`'s bitmap.
    fn drawn(code: u8) -> [[f64; 8]; 8] {
        let bitmap = BITMAPS[usize::from(code - b' ')];
        std::array::from_fn(|row| {
            std::array::from_fn(|column| f64::from((bitmap[row] >> column) & 1) * 2.0)
        })
    }

    #[test]
    fn each_character_matches_its_own_bitmap() {
        // A cell drawn as a bitmap fits it with no error, so only a character with the same
        // bitmap could tie; the space, first, is chosen for an empty cell.
        assert_eq!(best(&[[0.0; 8]; 8]), b' ');
        for code in b'!'..=b'~' {
            // The character rides along so a failure names it.
            let chosen = best(&drawn(code));
            assert_eq!(
                (code as char, BITMAPS[usize::from(chosen - b' ')]),
                (code as char, BITMAPS[usize::from(code - b' ')])
            );
        }
    }
}
