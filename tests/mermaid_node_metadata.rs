//! Mermaid node metadata, `A@{ shape: .., label: .. }`, read as Mermaid 12.3.0 reads it.

use apollinaire_ascii::diagram::flowchart;

/// Each accepted chart draws exactly as the chart written with brackets beside it: every shape
/// is the same box, and `label` is the box's text.
#[test]
fn node_metadata_names_a_shape_and_label_as_brackets_do() {
    let same = [
        ("A@{ shape: rect }", "A"),
        ("A@{shape: diam}", "A"),
        ("A@{ shape: rect, label: Start here }", "A[Start here]"),
        (
            "A@{ label: \"Start, then } stop\" }",
            "A[\"Start, then } stop\"]",
        ),
        ("A@{ label: 'Start, then stop' }", "A[\"Start, then stop\"]"),
        ("A@{ label : x }", "A[x]"),
        ("A@{ label: a#b }", "A[a#b]"),
        ("A@{ label: x #59; y }", "A[x #59; y]"),
        ("A@{ label: x #00059; y }", "A[x #00059; y]"),
        ("A@{ label: \"a #; b\" }", "A[\"a #; b\"]"),
        (
            "A@{ label: \"a:#59; b\" } --> B[style]",
            "A[\"a:#59; b\"] --> B[style]",
        ),
        (
            "B[Style] --> A@{ label: \"a:#59; b\" }",
            "B[Style] --> A[\"a:#59; b\"]",
        ),
        (
            "B[style] --> A@{ label: \"a:b; c\" }",
            "B[style] --> A[\"a:b; c\"]",
        ),
        ("A@{ label: \"Lifestyle #1\" }", "A[\"Lifestyle #1\"]"),
        (
            "B[Lifestyle] --> A@{ label: \"Issue #3\" }",
            "B[Lifestyle] --> A[\"Issue #3\"]",
        ),
        (
            "A@{ label: \"style: #59; b\" }",
            "A[\"style: #59; b\"]",
        ),
        (
            "B[style:x] --> A@{ label: \"a #59; b\" }",
            "B[style:x] --> A[\"a #59; b\"]",
        ),
        ("A@{ shape: \"cyl\", label: Store }", "A[Store]"),
        ("A[Old]@{ label: New }", "A[New]"),
        (
            "A@{ shape: hex } --> B@{ shape: doc, label: Out }",
            "A --> B[Out]",
        ),
        ("A@{ shape: lean-r } & B --> C", "A & B --> C"),
        ("A@{ shape: rect } & B --> C", "A & B --> C"),
        ("A --> B\nB@{ label: Later }", "A --> B[Later]"),
        ("A@{ label: First }\nA[Second]", "A[Second]"),
        ("A@{ shape: rect };B", "A;B"),
        ("A@{ }", "A"),
        ("A@{}", "A"),
        ("A@{ label: x}", "A[x]"),
        ("A@{ label: \"  x  \" }", "A[x]"),
        ("A@{ shape: rect , label: x }", "A[x]"),
        ("A@{ label: a:b }", "A[a:b]"),
        ("A@{ label: x #lt; y }", "A[x #lt; y]"),
        ("A[Old]@{ shape: hex }", "A[Old]"),
        (
            "L_1_2 --> L_a_b_c & L_a_b_ & L --> L_a_b_1x",
            "L_1_2 --> L_a_b_c & L_a_b_ & L --> L_a_b_1x",
        ),
        ("A@{ label: \"a^b\" }", "A[\"a^b\"]"),
        (
            "A@{ label: x }
A@{ shape: hex }",
            "A[x]",
        ),
    ];
    let shapes = [
        "rect",
        "proc",
        "process",
        "rectangle",
        "rounded",
        "event",
        "stadium",
        "terminal",
        "pill",
        "fr-rect",
        "subprocess",
        "subproc",
        "framed-rectangle",
        "subroutine",
        "cyl",
        "db",
        "database",
        "cylinder",
        "datastore",
        "data-store",
        "folder",
        "directory",
        "bucket",
        "console",
        "browser",
        "person",
        "circle",
        "circ",
        "bang",
        "cloud",
        "diam",
        "decision",
        "diamond",
        "question",
        "hex",
        "hexagon",
        "prepare",
        "lean-r",
        "lean-right",
        "in-out",
        "lean-l",
        "lean-left",
        "out-in",
        "trap-b",
        "priority",
        "trapezoid-bottom",
        "trapezoid",
        "trap-t",
        "manual",
        "trapezoid-top",
        "inv-trapezoid",
        "dbl-circ",
        "double-circle",
        "doublecircle",
        "text",
        "notch-rect",
        "card",
        "notched-rectangle",
        "lin-rect",
        "lined-rectangle",
        "lined-process",
        "lin-proc",
        "shaded-process",
        "brace",
        "comment",
        "brace-l",
        "brace-r",
        "braces",
        "doc",
        "document",
        "delay",
        "half-rounded-rectangle",
        "h-cyl",
        "das",
        "horizontal-cylinder",
        "lin-cyl",
        "disk",
        "lined-cylinder",
        "curv-trap",
        "curved-trapezoid",
        "display",
        "div-rect",
        "div-proc",
        "divided-rectangle",
        "divided-process",
        "tri",
        "extract",
        "triangle",
        "win-pane",
        "internal-storage",
        "window-pane",
        "notch-pent",
        "loop-limit",
        "notched-pentagon",
        "flip-tri",
        "manual-file",
        "flipped-triangle",
        "sl-rect",
        "manual-input",
        "sloped-rectangle",
        "docs",
        "documents",
        "st-doc",
        "stacked-document",
        "st-rect",
        "procs",
        "processes",
        "stacked-rectangle",
        "bow-rect",
        "stored-data",
        "bow-tie-rectangle",
        "tag-doc",
        "tagged-document",
        "tag-rect",
        "tagged-rectangle",
        "tag-proc",
        "tagged-process",
        "flag",
        "paper-tape",
        "odd",
        "lin-doc",
        "lined-document",
    ];
    let mut wrong = Vec::new();
    let draw = |body: &str| flowchart(&format!("flowchart LR\n{body}"));
    for (body, brackets) in same {
        let (got, want) = (draw(body), draw(brackets));
        if got.is_err() || got.as_ref().map(|f| f.text()) != want.as_ref().map(|f| f.text()) {
            wrong.push(format!("{body:?}: {:?}", got.map(|f| f.text())));
        }
    }
    for shape in shapes {
        let body = format!("A@{{ shape: {shape}, label: Box }}");
        if draw(&body).map(|f| f.text()) != draw("A[Box]").map(|f| f.text()) {
            wrong.push(format!("{body:?}: {:?}", draw(&body).map(|f| f.text())));
        }
    }
    assert!(wrong.is_empty(), "drawn wrongly:\n{}", wrong.join("\n"));
}
